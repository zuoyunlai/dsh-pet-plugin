function build(lang, over) {
  const out = { meta: { ...en.meta }, pet: {} }
  for (const [k, v] of Object.entries(en.pet)) out.pet[k] = v
  for (const [k, v] of Object.entries(over)) {
    if (k.startsWith('meta.')) out.meta[k.slice(5)] = Array.isArray(v) ? v[1] : v
    else out.pet[k] = v
  }
  // meta.title 跟随语言（英文名保留品牌）
  Object.assign(out.pet, A11Y[lang] || {})
  if (lang === 'zh') out.meta.title = '桌面伴侣'
  else if (lang === 'es') out.meta.title = 'Compañera de escritorio'
  else if (lang === 'pt') out.meta.title = 'Companheira de mesa'
  else if (lang === 'hi') out.meta.title = 'Desktop Companion'
  fs.writeFileSync(`locale/${lang}.json`, JSON.stringify(out, null, 2) + '\n')
  return Object.keys(out.pet).length
}

